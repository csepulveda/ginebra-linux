#!/bin/bash
# make-floppies.sh - Create floppy1-boot.img (FAT12 + SYSLINUX 4.07 + kernel)
#                    and floppy2-rootfs.img (ext2 rootfs) without root/loop mounts.
# Run inside the build container (see scripts/build.sh). Output goes to out/.
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/out"; DL="$ROOT/dl"; STAGE="$OUT/rootfs"
KERNEL="$ROOT/linux/arch/x86/boot/bzImage"
KVER=$(make -s -C "$ROOT/linux" kernelrelease)
SYSLINUX_VER=4.07
# Same identifiers as the original disks, so new disks are structurally identical
FAT_SERIAL=${FAT_SERIAL:-CBE3DAE2}
EXT2_UUID=${EXT2_UUID:-4e0a83f5-6e98-444d-b847-aa26ddc28dbf}

mkdir -p "$OUT" "$DL"

# --- SYSLINUX 4.07 (newer versions don't fit next to the kernel) ---
if [ ! -x "$DL/syslinux-$SYSLINUX_VER/mtools/syslinux" ]; then
    [ -f "$DL/syslinux-$SYSLINUX_VER.tar.gz" ] || wget -q -O "$DL/syslinux-$SYSLINUX_VER.tar.gz" \
        "https://mirrors.edge.kernel.org/pub/linux/utils/boot/syslinux/4.xx/syslinux-$SYSLINUX_VER.tar.gz"
    tar --no-same-owner -xzf "$DL/syslinux-$SYSLINUX_VER.tar.gz" -C "$DL"
fi

# --- Floppy 1: boot ---
rm -f "$OUT/floppy1-boot.img"
mkfs.vfat -C -n BOOT -i "$FAT_SERIAL" "$OUT/floppy1-boot.img" 1440 >/dev/null
"$DL/syslinux-$SYSLINUX_VER/mtools/syslinux" --install "$OUT/floppy1-boot.img"
mcopy -m -i "$OUT/floppy1-boot.img" "$KERNEL" ::/bzImage
mcopy -m -i "$OUT/floppy1-boot.img" "$ROOT/syslinux.cfg" ::/syslinux.cfg
echo "== floppy1-boot.img"; mdir -i "$OUT/floppy1-boot.img" ::/

# --- Floppy 2: rootfs ---
rm -rf "$STAGE"; mkdir -p "$STAGE"
cp -a "$ROOT/filesystem/." "$STAGE/"
# Files generated by mia (e.g. etc/ginebra.conf) override filesystem/
[ -d "$OUT/overlay" ] && cp -a "$OUT/overlay/." "$STAGE/"
mkdir -p "$STAGE"/{dev,proc,sys,tmp,home} "$STAGE/lib/modules/$KVER"
find "$ROOT/linux" -name "*.ko" -exec cp {} "$STAGE/lib/modules/$KVER/" \;
depmod -b "$STAGE" -a "$KVER"
chmod 0755 "$STAGE"/{dev,proc,sys,tmp,home}

rm -f "$OUT/floppy2-rootfs.img"
mkfs.ext2 -q -F -b 4096 -N 192 -I 256 -m 5 -L ROOTFS -U "$EXT2_UUID" \
    -E root_owner=0:0 -d "$STAGE" "$OUT/floppy2-rootfs.img" 360
# Static device nodes needed before devtmpfs is mounted
debugfs -w -f - "$OUT/floppy2-rootfs.img" >/dev/null <<DBG
cd /dev
mknod console c 5 1
mknod null c 1 3
sif console mode 020644
sif null mode 020644
DBG
e2fsck -fn "$OUT/floppy2-rootfs.img" >/dev/null
echo "== floppy2-rootfs.img"; dumpe2fs -h "$OUT/floppy2-rootfs.img" 2>/dev/null | grep -E "Block count|Free blocks|Inode count|Free inodes"
